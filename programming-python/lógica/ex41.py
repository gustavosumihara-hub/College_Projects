idade=int(input('informe sua idade '))
if idade<=9:
    print('Você é um atleta mirim ')
elif 9<idade<=14:
    print('Você é um atleta infantil ')
elif 14<idade<=19:
    print('Você é um atleta junior')
elif 19<idade<=25:
    print('Você é um atleta senior ')
else:
    print('Voce é um atleta master ')
